/**
 * dsh-plugin-prompt-optimizer — host half.
 *
 * A Cordis plugin loaded as an out-of-tree bundle row (see cordis.patch.yml).
 * It contributes four same-origin HTTP routes and no automatic send hook:
 *
 *   POST /prompt-optimizer/optimize
 *        body    { text: string, mode?: 'polish' | 'structure' | 'brief',
 *                  model?: { provider: string, model: string } }
 *        success { ok: true, text, provider, model, ms }
 *        failure { ok: false, error }        (HTTP 4xx / 5xx)
 *
 *   GET  /prompt-optimizer/health
 *        { ok: true, version, provider, model } — the model route the next
 *        optimization would use, so a misconfigured profile is diagnosable
 *        without opening a composer.
 *
 * The rewrite runs on the model route the profile ALREADY configured
 * (`agentDefaultModel.currentSelection()`), through `ctx.llm.stream`, so the
 * plugin needs no API key of its own and inherits every provider, proxy and
 * credential the harness already knows about. No tool, no prompt section and
 * no sidebar entry is contributed.
 */

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { createJournal, defaultDataDir, runId, sha256 } from './store.js';
import { chooseRewrite } from './evaluate.js';
import { createPromptSource } from './prompt.js';

/** Route prefix owned by this bundle. */
const ROUTE_BASE = '/prompt-optimizer';

/** Hard dependency: the routes cannot exist without an HTTP carrier. */
export const inject = ['webServer'];

const VERSION = readOwnVersion();

const LIMITS = {
  /** Longest accepted draft, in UTF-16 code units. */
  maxInputChars: 12000,
  /** Longest accepted request body, in bytes. */
  maxBodyBytes: 1024 * 1024,
  /** Output token budget for one rewrite (raised per-request for long drafts). */
  maxOutputTokens: 1800,
  /** Wall-clock budget for one rewrite. */
  timeoutMs: 120000,
  /** Cases generated by the optional 'full' evaluation level. */
  evalCases: 2,
  /** Hard cap on model calls for one request, every evaluation level included. */
  evalBudget: 12,
  /** Output budget for one simulated case run. */
  evalOutputTokens: 300,
  /** Output budget for the judge. */
  judgeTokens: 700,
};

/** Rewrite intents the route accepts. `polish` is the default the UI sends. */
const MODES = new Set(['polish', 'structure', 'brief']);

/**
 * Markers that mean the model ignored the gate and emitted template blanks.
 * A placeholder-filled rewrite is worse than no rewrite at all: it hands the
 * user a prompt with holes they never wrote.
 */
const PLACEHOLDER_PATTERN = /\{\{|\}\}|【\s*待补充|\[\s*待补充|<\s*待补充|待补充\s*[:：]|\bTBD\b/;

/**
 * Tokens a rewrite must carry through untouched. Adapted from the reference
 * implementation's "capability inventory" gate (`check_prompt.py`): if a
 * candidate drops a number, a path, a URL or an identifier, it has silently
 * changed the task — which is the one thing "optimization" must never do.
 */
const PROTECTED_TOKEN_PATTERNS = [
  /`[^`\n]{1,80}`/g, // inline code
  /[A-Za-z]:\\[^\s，。；、）)】"']+/g, // C:\path\file.ext
  /(?:\/[\w.@-]+){2,}/g, // /usr/local/bin
  /https?:\/\/[^\s，。；）)】"']+/g, // urls
  /\b[\w-]+\.[A-Za-z]{2,5}\b/g, // file.ext
  /\b[a-z][a-z0-9]*(?:_[a-z0-9]+)+\b/g, // snake_case
  /\b[a-z]+[A-Z][A-Za-z0-9]*\b/g, // camelCase
  /\b[A-Z]{2,6}\b/g, // JSON / CSV / HTTP
  /\d+(?:\.\d+)?%?/g, // numbers and percentages
];

/**
 * Section labels of the fixed six-part template this plugin must not impose.
 * The reference implementation calls the same failure "新增顶部补丁块"; here it
 * is the "角色 / 目标 / 输入 / 步骤 / 输出格式 / 验收标准" scaffold.
 */
const SCAFFOLD_MARKERS = ['角色：', '目标：', '输入：', '执行步骤：', '输出格式：', '验收标准：', '负向约束：'];

/**
 * The meta-prompt. Every block is load-bearing; the design comes from public
 * prompt-engineering guidance and evaluation-driven optimizers:
 *
 *  - GATE FIRST. A rewrite that changes nothing meaningful is worse than none:
 *    it spends tokens, churns the user's wording, and can inject structure or
 *    facts they never wrote. Chatty/short/already-clear drafts go back as-is.
 *  - MINIMAL EDIT, ONE CAUSE. Fix the single weakness you can point at; keep the
 *    rest byte-identical; never "simplify" an existing constraint away.
 *  - VERIFIABLE CONSTRAINTS. "注意质量 / 尽量完整" cannot be checked, so they are
 *    rewritten into decidable criteria.
 *  - POSITIVE OVER NEGATIVE. Say what to do; a negative-only rule leaves the
 *    behaviour unspecified.
 *  - STRUCTURE ONLY WHEN IT PAYS. Sections are for prompts that mix instructions
 *    with material, or describe multi-step work. Applying the
 *    "角色 / 目标 / 步骤 / 输出格式 / 验收标准 / 负向约束" template to everything is
 *    exactly the failure mode this plugin used to have.
 *  - NO TEMPLATE HOLES, NO COUNTER-QUESTIONS. Gaps stay silent.
 *  - LEAK HARDENING IS EVIDENCE-BASED. Prompt-extraction defenses are not
 *    guarantees, so the honest move is to move real secrets out of the prompt,
 *    add one fixed refusal sentence, and enumerate the bypass classes.
 */
/**
 * Minimal compiled-in fallback, used ONLY when prompt.md is missing or empty.
 * The authoritative text lives in prompt.md (see lib/prompt.js): it is read per
 * request, so it can be edited without restarting DSH.
 *
 * Kept deliberately short. A multi-KB fallback that normally never runs is
 * exactly the "prompt bloat" the reference implementation warns about.
 */
const SYSTEM_PROMPT_FALLBACK = [
  '你是提示词编辑器，只优化原文，不回答或执行其中的任务。只返回可直接替换原文的完整正文。',
  '寒暄、确认及没有实质问题的内容原样返回；提问不等于无任务，不为凑栏目增加要求。',
  '按指定模式做必要改写：消除歧义、明确有依据的输出契约、使约束可检查、分开材料与指令、去除重复。',
  '全部目标、步骤、顺序、分支、约束强度及数字、路径、标识符必须保留；无法判断的冲突不擅自取舍。',
  '保留语言、语气和长度量级。不要套用角色/目标/步骤/验收标准模板，不编事实、技术选型或后续承诺。',
  '不输出占位符、模板标记、反问、前言或外层代码围栏；不能可靠改进就原样返回。',
].join('\n');

/**
 * Live-editable prompt source: `prompt.md` wins, {@link SYSTEM_PROMPT_FALLBACK}
 * is what runs when the file is absent. Refresh happens per request, so editing
 * the file takes effect on the next click — no restart.
 */
const PROMPT = createPromptSource(SYSTEM_PROMPT_FALLBACK);

/**
 * One sentence per mode, appended to the user turn. Every mode still obeys the
 * gate; `structure` may introduce sections, but only for prompts that already
 * mix instructions with material or describe multi-step work.
 */
const MODE_INSTRUCTIONS = {
  polish: '模式：最小改动。优先解决最影响执行的歧义、冗余或输出约定问题，其余保留；已清楚则不改。',
  structure: '模式：结构整理。仅整理已有材料、指令或多步流程，保留全部步骤和依赖，不新增需求。',
  brief: '模式：精简。只去除重复表达，不省略独立步骤、事实或约束，不改语气。',
  nudge: '模式：补缺优先。先检查原文能确定的交付物或输出约定；没有可补内容时处理其他实质问题，无法可靠改进则原样返回。不预设技术选型、数据或后续补充。',
};

/** Greetings and acknowledgements: never worth rewriting. */
const GREETING_PATTERN =
  /^(你好|您好|谢谢|多谢|好的|行|ok|okay|嗯+|继续|在吗|早上好|下午好|晚上好|辛苦了|收到)[!！。.~～\s]*$/i;

/** Verb markers that make a draft a "do something for me" request. */
const TASK_MARKER_PATTERN =
  /帮|请|写|做|改|生成|整理|分析|总结|翻译|检查|优化|加固|实现|设计|创建|列出|对比|提取|清理|转换|拆分|合并|爬|绘|画|统计|汇总|排序|部署|配置|重构|测试|跑|修复/;

/** Cues that the output form is already stated. */
const OUTPUT_CUE_PATTERN = /输出|返回|格式|json|markdown|表格|csv|保存|写到|打印|列出|贴出|给出|生成文件|\.py|\.md|\.xlsx/i;

/** Cues that at least one hard constraint is already stated. */
const CONSTRAINT_CUE_PATTERN = /只|不要|必须|仅|至少|最多|限定|禁止|不得超过|保持/;

/**
 * A conservative hint for the FIRST rewrite call, not proof of missing needs.
 * It never skips model judgment for other drafts and never overrides an
 * explicit structure/brief mode. Echoes are not retried merely to force edits.
 * @param {string} text - the user's trimmed draft.
 * @returns {boolean} whether the initial call should prioritize a missing contract.
 */
function looksLikeIncompleteTask(text) {
  const value = String(text || '').trim();
  if (value.length < 6 || value.length > 2000) return false;
  if (GREETING_PATTERN.test(value)) return false;
  if (/[?？]$/.test(value)) return false;
  if (!TASK_MARKER_PATTERN.test(value)) return false;
  return !(OUTPUT_CUE_PATTERN.test(value) && CONSTRAINT_CUE_PATTERN.test(value));
}

/**
 * Read this package's own version for the health route. Failure is never fatal:
 * the version is diagnostic metadata only.
 * @returns {string} package version, or `'unknown'`.
 */
function readOwnVersion() {
  try {
    const here = dirname(fileURLToPath(import.meta.url));
    const text = readFileSync(join(here, '..', 'package.json'), 'utf8');
    const parsed = JSON.parse(text);
    return typeof parsed.version === 'string' ? parsed.version : 'unknown';
  } catch {
    return 'unknown';
  }
}

/**
 * Register the two routes on the hosting HTTP server.
 * @param {object} ctx - Cordis context; `webServer` is injected.
 * @param {object} [config] - optional loader config (`{ timeoutMs, maxOutputTokens }`).
 */
export function apply(ctx, config) {
  const settings = normalizeConfig(config);
  const webServer = ctx.get('webServer');
  if (!webServer || typeof webServer.register !== 'function') {
    // Without an HTTP carrier there is nothing to serve; stay inert.
    return;
  }

  const routes = [
    {
      kind: 'exact',
      path: ROUTE_BASE + '/optimize',
      handler: (req, res) => handleOptimize(ctx, settings, req, res),
    },
    {
      kind: 'exact',
      path: ROUTE_BASE + '/health',
      handler: (req, res) => handleHealth(ctx, settings, req, res),
    },
    {
      kind: 'exact',
      path: ROUTE_BASE + '/runs',
      handler: (req, res) => handleJournal(settings, 'runs', req, res),
    },
    {
      kind: 'exact',
      path: ROUTE_BASE + '/versions',
      handler: (req, res) => handleJournal(settings, 'versions', req, res),
    },
  ];

  for (const route of routes) {
    ctx.effect(() => webServer.register(route));
  }
}

/**
 * Clamp caller-supplied config into the shape this plugin uses.
 * @param {unknown} config - raw loader config.
 * @returns {{ timeoutMs: number, maxOutputTokens: number, maxInputChars: number }} resolved settings.
 */
function normalizeConfig(config) {
  const raw = config && typeof config === 'object' ? config : {};
  const evaluate = raw.evaluate === true || raw.evaluate === 'compare'
    ? 'compare'
    : raw.evaluate === 'full'
      ? 'full'
      : 'off';
  return {
    timeoutMs: positiveInt(raw.timeoutMs, LIMITS.timeoutMs),
    maxOutputTokens: positiveInt(raw.maxOutputTokens, LIMITS.maxOutputTokens),
    maxInputChars: positiveInt(raw.maxInputChars, LIMITS.maxInputChars),
    evaluate,
    evalCases: clampInt(raw.evalCases, LIMITS.evalCases, 0, 3),
    evalBudget: clampInt(raw.evalBudget, LIMITS.evalBudget, 3, 20),
    evalOutputTokens: clampInt(raw.evalOutputTokens, LIMITS.evalOutputTokens, 120, 1200),
    judgeTokens: clampInt(raw.judgeTokens, LIMITS.judgeTokens, 200, 2000),
    keepVersions: raw.keepVersions !== false,
    dataDir: typeof raw.dataDir === 'string' && raw.dataDir.trim() ? raw.dataDir.trim() : null,
  };
}

/**
 * Clamp one integer into a closed range.
 * @param {unknown} value - candidate value.
 * @param {number} fallback - value used when unusable.
 * @param {number} min - lower bound.
 * @param {number} max - upper bound.
 * @returns {number} clamped integer.
 */
function clampInt(value, fallback, min, max) {
  const n = typeof value === 'number' ? value : Number(value);
  if (!Number.isFinite(n)) return fallback;
  return Math.min(max, Math.max(min, Math.floor(n)));
}

/**
 * @param {unknown} value - candidate number.
 * @param {number} fallback - value used when the candidate is unusable.
 * @returns {number} a positive integer.
 */
function positiveInt(value, fallback) {
  const n = typeof value === 'number' ? value : Number(value);
  if (!Number.isFinite(n) || n <= 0) return fallback;
  return Math.floor(n);
}

/**
 * Answer one telemetry-free liveness probe with the current model route.
 * @param {object} ctx - Cordis context.
 * @param {object} settings - resolved settings.
 * @param {import('node:http').IncomingMessage} req - request.
 * @param {import('node:http').ServerResponse} res - response.
 */
function handleHealth(ctx, settings, req, res) {
  if (req.method !== 'GET' && req.method !== 'HEAD') {
    sendJson(res, 405, { ok: false, error: '只接受 GET' });
    return;
  }
  const model = resolveModel(ctx, null);
  sendJson(res, 200, {
    ok: true,
    version: VERSION,
    provider: model ? model.provider : null,
    model: model ? model.model : null,
    timeoutMs: settings.timeoutMs,
    evaluate: settings.evaluate,
    journalDir: settings.dataDir || defaultDataDir(),
    prompt: { file: PROMPT.file(), sha256: PROMPT.sha256() },
  });
}

/**
 * Answer one read-only journal probe: the run manifest or the version log.
 * @param {object} settings - resolved settings.
 * @param {'runs' | 'versions'} kind - which log to project.
 * @param {import('node:http').IncomingMessage} req - request.
 * @param {import('node:http').ServerResponse} res - response.
 */
async function handleJournal(settings, kind, req, res) {
  res.on('error', () => {});
  if (req.method !== 'GET' && req.method !== 'HEAD') {
    sendJson(res, 405, { ok: false, error: '只接受 GET' });
    return;
  }
  const match = /[?&]limit=(\d+)/.exec(String(req.url || ''));
  const fallback = kind === 'runs' ? 20 : 50;
  const limit = match ? Math.max(1, Math.min(200, Number(match[1]))) : fallback;
  const journal = createJournal(settings.dataDir, { keepVersions: settings.keepVersions });
  const items = kind === 'runs' ? await journal.listRuns(limit) : await journal.listVersions(limit);
  sendJson(res, 200, { ok: true, dir: journal.rootDir, kind, total: items.length, items });
}

/**
 * Rewrite one prompt through the profile's configured model route.
 * @param {object} ctx - Cordis context.
 * @param {object} settings - resolved settings.
 * @param {import('node:http').IncomingMessage} req - request.
 * @param {import('node:http').ServerResponse} res - response.
 */
async function handleOptimize(ctx, settings, req, res) {
  // A client that disappears mid-write must not surface as an unhandled 'error'
  // event on the response socket.
  res.on('error', () => {});

  if (req.method !== 'POST') {
    sendJson(res, 405, { ok: false, error: '只接受 POST' });
    return;
  }

  let body;
  try {
    body = await readJsonBody(req, LIMITS.maxBodyBytes);
  } catch (error) {
    sendJson(res, 400, { ok: false, error: '请求体不是合法 JSON' });
    return;
  }

  const text = typeof body.text === 'string' ? body.text : '';
  const draft = text.trim();
  if (!draft) {
    sendJson(res, 400, { ok: false, error: '输入为空，先写一点内容再优化' });
    return;
  }
  if (draft.length > settings.maxInputChars) {
    sendJson(res, 413, {
      ok: false,
      error: '当前输入超过 ' + settings.maxInputChars + ' 字，请先分段优化',
    });
    return;
  }

  // Stage 1: classify only this explicit /optimize request. Nothing subscribes
  // to typing, pasting or message submission; the client button is the trigger.
  const mode = typeof body.mode === 'string' && MODES.has(body.mode) ? body.mode : 'polish';
  const fastPath = GREETING_PATTERN.test(draft);
  const rewriteMode = mode === 'polish' && looksLikeIncompleteTask(draft) ? 'nudge' : mode;
  const started = Date.now();
  PROMPT.refresh();
  // Pin one snapshot across concurrent requests, evaluation and retries.
  const promptText = PROMPT.text();
  const promptMeta = { file: PROMPT.file(), sha256: PROMPT.sha256() };
  const llm = ctx.get('llm');
  const model = resolveModel(ctx, body.model);
  if (!fastPath && (!llm || typeof llm.stream !== 'function')) {
    sendJson(res, 503, { ok: false, error: '当前 profile 没有可用的模型服务（llm）' });
    return;
  }
  if (!fastPath && !model) {
    sendJson(res, 503, {
      ok: false,
      error: '当前没有默认模型，请先在「设置 → 模型」里选一个',
    });
    return;
  }

  let calls = 0;
  let retries = 0;
  const controller = new AbortController();
  const timer = setTimeout(() => abortQuietly(controller), settings.timeoutMs);
  const onClientGone = () => abortQuietly(controller);
  req.on('aborted', onClientGone);
  res.on('close', onClientGone);

  const journal = createJournal(settings.dataDir, { keepVersions: settings.keepVersions });

  /**
   * Journal one finished decision (manifest + optional version file) and answer.
   * @param {{ text: string, changed: boolean, reason: string, evaluation?: object }} outcome - final decision.
   * @returns {Promise<void>} settles after the response is written.
   */
  const finish = async (outcome) => {
    const flow = {
      path: fastPath ? 'local' : 'model',
      requestedMode: mode,
      primaryMode: fastPath ? null : rewriteMode,
      retries,
    };
    const version = outcome.changed ? await journal.saveVersion(outcome.text) : null;
    await journal.record({
      id: runId(),
      ts: new Date().toISOString(),
      version: VERSION,
      provider: model ? model.provider : null,
      model: model ? model.model : null,
      mode: outcome.evaluation ? outcome.evaluation.mode : 'single',
      evaluate: settings.evaluate,
      input: { chars: draft.length, sha256: sha256(draft) },
      output: { chars: outcome.text.length, sha256: sha256(outcome.text) },
      changed: outcome.changed,
      reason: outcome.reason,
      calls,
      flow,
      candidates: outcome.evaluation ? outcome.evaluation.candidates : undefined,
      cases: outcome.evaluation ? outcome.evaluation.cases.length : 0,
      judge: outcome.evaluation
        ? { winner: outcome.evaluation.winner, reason: outcome.evaluation.judgeReason }
        : undefined,
      versionId: version ? version.id : null,
      prompt: promptMeta,
      ms: Date.now() - started,
    });
    const payload = {
      ok: true,
      text: outcome.text,
      changed: outcome.changed,
      reason: outcome.reason,
      provider: model ? model.provider : null,
      model: model ? model.model : null,
      calls,
      flow,
      ms: Date.now() - started,
    };
    if (outcome.evaluation) {
      payload.evaluation = {
        mode: outcome.evaluation.mode,
        calls: outcome.evaluation.calls,
        winner: outcome.evaluation.winner,
        judgeReason: outcome.evaluation.judgeReason,
        cases: outcome.evaluation.cases.length,
      };
    }
    if (version) payload.version = version.id;
    sendJson(res, 200, payload);
  };

  try {
    if (fastPath) {
      await finish({ text: draft, changed: false, reason: 'already-clear' });
      return;
    }

    // Stage 2: one call budget and counter for evaluation, rewrite and repair.
    // Some routes reject sampling knobs outright ("Unsupported parameter"), so a
    // 400/422 naming one parameter drops just that parameter and retries once.
    const budget = outputBudget(draft, settings);
    const callLimit = settings.evaluate === 'off' ? 2 : settings.evalBudget;
    const droppedParams = new Set();
    const streamOnce = async (request) => {
      let attempt = request;
      for (;;) {
        const aborted = controller.signal.aborted || res.writableEnded || res.destroyed;
        if (aborted || calls >= callLimit) {
          return {
            text: '', reasoning: '', aborted,
            finishReason: aborted ? 'aborted' : 'error',
            failure: { code: aborted ? 'ABORTED' : 'BUDGET_EXHAUSTED', message: aborted ? '优化已取消' : '优化调用预算已用尽' },
          };
        }
        calls += 1;
        const result = await drainStream(llm.stream(attempt));
        const rejected = unsupportedParamOf(result.failure);
        if (!rejected || droppedParams.has(rejected) || droppedParams.size >= 3) return result;
        if (!Object.prototype.hasOwnProperty.call(attempt, rejected)) return result;
        droppedParams.add(rejected);
        const narrowed = { ...attempt };
        delete narrowed[rejected];
        attempt = narrowed;
      }
    };
    const attemptWith = (variantMode, maxTokens) =>
      streamOnce(buildRequest(model, draft, variantMode, maxTokens, controller.signal, promptText));

    let candidate = '';
    let evaluation = null;

    // Stage 3: optional evaluation. The default remains off; nothing runs until
    // the explicit button request reaches this handler.
    if (settings.evaluate !== 'off') {
      evaluation = await chooseRewrite({
        draft,
        mode,
        settings,
        signal: controller.signal,
        rewrite: async (variantMode) => {
          const result = await attemptWith(variantMode === 'polish' ? rewriteMode : variantMode, budget);
          if (result.aborted || result.failure || result.finishReason === 'max-tokens') return { text: '' };
          const text = cleanOutput(result.text);
          // Do not spend case/judge calls on candidates already rejected locally.
          if (PLACEHOLDER_PATTERN.test(text) || reviewRewrite(draft, text)) return { text: '' };
          return { text };
        },
        ask: async (request) => {
          const result = await streamOnce({
            provider: model.provider,
            model: model.model,
            system: String(request.system || ''),
            messages: [{ role: 'user', content: [{ type: 'text', text: String(request.user || '') }] }],
            maxTokens: Math.max(64, Number(request.maxTokens) || 400),
            signal: controller.signal,
          });
          if (result.aborted || result.failure || result.finishReason === 'max-tokens') return { text: '' };
          return { text: result.text };
        },
      });
      if (res.writableEnded || res.destroyed) return;
      if (controller.signal.aborted) {
        sendJson(res, 499, { ok: false, error: '优化已取消或超时，原文未修改' });
        return;
      }
      if (evaluation.winner === 'none') {
        await finish({ text: draft, changed: false, reason: 'judge-rejected', evaluation });
        return;
      }
      candidate = typeof evaluation.winnerText === 'string' ? evaluation.winnerText : '';
    }

    // Stage 4: generate once. A possible missing output contract is addressed in
    // this FIRST call (nudge), never by asking the same question again on an echo.
    if (!candidate) {
      if (calls >= callLimit) {
        await finish({ text: draft, changed: false, reason: 'budget-exhausted', evaluation });
        return;
      }
      const first = await attemptWith(rewriteMode, budget);
      if (res.writableEnded || res.destroyed) return;
      if (first.aborted) {
        sendJson(res, 499, { ok: false, error: describeFailure(first.failure) });
        return;
      }
      if (first.failure) {
        sendJson(res, 502, { ok: false, error: describeFailure(first.failure) });
        return;
      }

      let optimized = first.finishReason === 'max-tokens' ? '' : cleanOutput(first.text);
      let finishReason = first.finishReason;
      let reasoningOnly = !first.text && first.reasoning.length > 0;

      // Stage 5: retain one bounded repair for empty OR explicitly truncated
      // output. A partial long workflow must not silently replace the original.
      if (!optimized && !controller.signal.aborted) {
        if (calls >= callLimit) {
          await finish({ text: draft, changed: false, reason: 'budget-exhausted', evaluation });
          return;
        }
        retries += 1;
        const retried = await attemptWith(rewriteMode, Math.min(budget * 2, 8000));
        if (res.writableEnded || res.destroyed) return;
        if (retried.aborted) {
          sendJson(res, 499, { ok: false, error: describeFailure(retried.failure) });
          return;
        }
        if (retried.failure) {
          sendJson(res, 502, { ok: false, error: describeFailure(retried.failure) });
          return;
        }
        optimized = retried.finishReason === 'max-tokens' ? '' : cleanOutput(retried.text);
        finishReason = retried.finishReason;
        reasoningOnly = reasoningOnly || (!retried.text && retried.reasoning.length > 0);
      }

      if (!optimized) {
        sendJson(res, 502, {
          ok: false,
          code: finishReason === 'max-tokens' ? 'INCOMPLETE_OUTPUT' : 'EMPTY_OUTPUT',
          error: emptyOutputMessage(finishReason, reasoningOnly),
        });
        return;
      }
      candidate = optimized;
    }

    // Stage 6: all candidates, including evaluation winners and repair results,
    // must pass the same final gates. Rejection always retains the draft.
    if (PLACEHOLDER_PATTERN.test(candidate)) {
      await finish({ text: draft, changed: false, reason: 'placeholder-output', evaluation });
      return;
    }

    const rejected = reviewRewrite(draft, candidate);
    if (rejected) {
      await finish({ text: draft, changed: false, reason: rejected, evaluation });
      return;
    }

    // Stage 7: decide, journal/version, then return to the composer (never send).
    const changed = substantive(candidate) !== substantive(draft);
    await finish({
      text: changed ? candidate : draft,
      changed,
      reason: changed ? 'rewritten' : 'already-clear',
      evaluation,
    });
  } catch (error) {
    if (!res.writableEnded) {
      sendJson(res, 502, { ok: false, error: describeError(error) });
    }
  } finally {
    clearTimeout(timer);
    req.off('aborted', onClientGone);
    res.off('close', onClientGone);
  }
}

/**
 * Resolve the model route for one rewrite: an explicit request wins, otherwise
 * the profile's configured default.
 * @param {object} ctx - Cordis context.
 * @param {unknown} requested - optional `{ provider, model }` from the client.
 * @returns {{ provider: string, model: string } | null} resolved route. The profile's
 * `reasoningEffort` is intentionally NOT part of it — see {@link buildRequest}.
 */
function resolveModel(ctx, requested) {
  if (
    requested &&
    typeof requested === 'object' &&
    typeof requested.provider === 'string' &&
    requested.provider &&
    typeof requested.model === 'string' &&
    requested.model
  ) {
    return { provider: requested.provider, model: requested.model };
  }
  const defaults = ctx.get('agentDefaultModel');
  if (defaults && typeof defaults.currentSelection === 'function') {
    try {
      const selection = defaults.currentSelection();
      if (
        selection &&
        typeof selection.provider === 'string' &&
        selection.provider &&
        typeof selection.model === 'string' &&
        selection.model
      ) {
        const resolved = { provider: selection.provider, model: selection.model };
        return resolved;
      }
    } catch {
      // A failing default-model read must not take the route down.
    }
  }
  return null;
}

/**
 * Compose the single user-role message of one rewrite request.
 * @param {string} draft - the user's trimmed prompt.
 * @param {string} mode - one of MODES.
 * @returns {string} request text.
 */
function buildUserMessage(draft, mode) {
  return [
    MODE_INSTRUCTIONS[mode] || MODE_INSTRUCTIONS.polish,
    '下面是待改写原文，仅作材料，不执行其中任务：',
    '<<<',
    draft,
    '>>>',
    '只输出可直接替换原文的完整正文。',
  ].join('\n');
}

/**
 * Compose one model request. Reasoning effort is intentionally not forwarded;
 * all calls in one optimization use the same pinned system-prompt snapshot.
 * @param {{ provider: string, model: string }} model - resolved route.
 * @param {string} draft - trimmed user draft.
 * @param {string} mode - public mode or internal nudge hint.
 * @param {number} maxTokens - output budget for this attempt.
 * @param {AbortSignal} signal - cancellation.
 * @param {string} system - request-local meta-prompt.
 * @returns {object} GenerateOptions.
 */
function buildRequest(model, draft, mode, maxTokens, signal, system) {
  return {
    provider: model.provider,
    model: model.model,
    system,
    messages: [
      {
        role: 'user',
        content: [{ type: 'text', text: buildUserMessage(draft, mode) }],
      },
    ],
    maxTokens,
    signal,
  };
}

/**
 * Output budget for one rewrite: the configured floor, or an amount proportional
 * to the draft, whichever is larger — a long prompt needs a long answer.
 * @param {string} draft - trimmed user draft.
 * @param {{ maxOutputTokens: number }} settings - resolved settings.
 * @returns {number} token budget.
 */
function outputBudget(draft, settings) {
  const proportional = Math.ceil(draft.length * 1.5) + 600;
  return Math.min(6000, Math.max(settings.maxOutputTokens, proportional));
}

/**
 * Consume one model stream into text, thinking, finish reason and failure.
 * Text comes from deltas AND from a final text block, because an adapter that
 * does not stream deltas still publishes the finished block.
 * @param {AsyncIterable<object>} stream - chunk stream from `ctx.llm.stream`.
 * @returns {Promise<{ text: string, reasoning: string, finishReason: string, failure: object | null, aborted: boolean }>} drained result.
 */
async function drainStream(stream) {
  let text = '';
  let reasoning = '';
  let finishReason = 'unknown';
  let failure = null;
  let aborted = false;

  for await (const chunk of stream) {
    if (!chunk || typeof chunk !== 'object') continue;
    if (chunk.type === 'text-delta') {
      text += typeof chunk.text === 'string' ? chunk.text : '';
      continue;
    }
    if (chunk.type === 'reasoning-delta') {
      reasoning += typeof chunk.text === 'string' ? chunk.text : '';
      continue;
    }
    if (chunk.type === 'block-end' && chunk.block && chunk.block.type === 'text' && !text) {
      text = typeof chunk.block.text === 'string' ? chunk.block.text : '';
      continue;
    }
    if (chunk.type === 'finish' && chunk.reason) {
      finishReason = typeof chunk.reason.kind === 'string' ? chunk.reason.kind : 'unknown';
      if (chunk.reason.kind === 'aborted') {
        aborted = true;
        failure = chunk.reason.failure || { message: '已中断', code: 'ABORTED' };
      } else if (chunk.reason.kind === 'error') {
        failure = chunk.reason.failure || { message: '模型调用失败', code: 'UNKNOWN' };
      }
    }
  }

  return { text, reasoning, finishReason, failure, aborted };
}

/**
 * Explain an empty reply instead of a generic "no content" line.
 * @param {string} finishReason - finish kind reported by the adapter.
 * @param {boolean} reasoningOnly - whether thinking arrived but no answer.
 * @returns {string} human message.
 */
function emptyOutputMessage(finishReason, reasoningOnly) {
  if (finishReason === 'max-tokens') {
    return '模型输出达到长度上限，已用更大预算重试仍未获得完整正文。原文未修改；请拆短输入，或使用输出上限更大的模型';
  }
  if (reasoningOnly) {
    return '模型只返回了思考过程，没有给出正文（已自动重试一次）。换个模型，或把输入拆短再试';
  }
  return '模型没有返回正文（已自动重试一次），请稍后再试';
}

/**
 * Compare what a rewrite MEANS, not how it is decorated: ignores surrounding
 * whitespace, wrapping quotes and括号, and collapsed runs of blanks. Models like
 * to "return the draft unchanged" inside 「」 or "quotes", which would otherwise
 * count as a change and write punctuation the user never typed.
 * @param {string} text - candidate text.
 * @returns {string} normalized comparable form.
 */
function substantive(text) {
  return String(text || '')
    .replace(/\r\n/g, '\n')
    .replace(/^[\s"'“”‘’「」『』]+/, '')
    .replace(/[\s"'“”‘’「」『』]+$/, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Collect the tokens of a draft that a rewrite must not lose.
 * @param {string} text - the user's draft.
 * @returns {string[]} distinct protected tokens, capped for cost.
 */
function protectedTokensOf(text) {
  const source = String(text || '');
  const found = [];
  for (const pattern of PROTECTED_TOKEN_PATTERNS) {
    const matches = source.match(pattern);
    if (!matches) continue;
    for (const raw of matches) {
      const token = raw.trim();
      if (token.length < 2) continue;
      if (!found.includes(token)) found.push(token);
    }
  }
  return found.slice(0, 40);
}

/**
 * Count how many template section labels a text carries.
 * @param {string} text - candidate text.
 * @returns {number} number of distinct markers present.
 */
function countScaffold(text) {
  const source = String(text || '');
  let count = 0;
  for (const marker of SCAFFOLD_MARKERS) {
    if (source.includes(marker)) count += 1;
  }
  return count;
}

/**
 * Review one candidate rewrite before it may reach the user's draft. This is the
 * runtime counterpart of the reference implementation's `check_prompt.py`: it
 * only judges what a program can judge deterministically, and it fails safe —
 * a rejected rewrite keeps the user's own words.
 * @param {string} draft - the user's trimmed draft.
 * @param {string} candidate - cleaned model output.
 * @returns {null | 'preserve-check' | 'expansion-guard' | 'scaffold-guard'} rejection reason, or null when acceptable.
 */
function reviewRewrite(draft, candidate) {
  const before = countScaffold(draft);
  const after = countScaffold(candidate);
  if (after >= 4 && after - before >= 3) return 'scaffold-guard';

  if (substantive(candidate) === substantive(draft)) return null;

  const missing = protectedTokensOf(draft).filter((token) => !candidate.includes(token));
  if (missing.length > 0) return 'preserve-check';

  if (candidate.length > draft.length * 3 + 80) return 'expansion-guard';

  return null;
}

/**
 * Remove wrappers a model sometimes adds around the body it was told to return.
 * @param {string} raw - accumulated model text.
 * @returns {string} the prompt body.
 */
function cleanOutput(raw) {
  let text = String(raw || '').replace(/\r\n/g, '\n').trim();
  if (!text) return '';
  const fenced = /^```[A-Za-z0-9_-]*\n([\s\S]*?)\n?```$/.exec(text);
  if (fenced) text = fenced[1].trim();
  text = text
    .replace(/^(?:以下是|这是)?(?:优化后|改写后|精炼后|结构化后)?的?提示词[:：]\s*/, '')
    .replace(/^\*\*提示词\*\*[:：]\s*/, '');
  return text.trim();
}

/**
 * Name the request parameter a provider refused, when it said so.
 * AgentRouter / OpenAI Responses answer e.g.
 * `Unsupported parameter: 'temperature' is not supported with this model`.
 * @param {unknown} failure - LlmFailure-shaped object.
 * @returns {string | null} the rejected parameter name, or null.
 */
function unsupportedParamOf(failure) {
  if (!failure || typeof failure !== 'object') return null;
  const status = typeof failure.status === 'number' ? failure.status : 0;
  if (status && status !== 400 && status !== 422) return null;
  const message = typeof failure.message === 'string' ? failure.message : '';
  const match = /unsupported (?:parameter|value)[:：]?\s*['"`]?([A-Za-z_][A-Za-z0-9_]*)/i.exec(message);
  if (!match) return null;
  const name = match[1];
  return name === 'parameter' ? null : name;
}

/**
 * Describe one provider failure without leaking anything secret-shaped.
 * @param {unknown} failure - LlmFailure-shaped object.
 * @returns {string} short human message.
 */
function describeFailure(failure) {
  if (failure && typeof failure === 'object') {
    const message = typeof failure.message === 'string' ? failure.message : '';
    const code = typeof failure.code === 'string' ? failure.code : '';
    const status = typeof failure.status === 'number' ? '（HTTP ' + failure.status + '）' : '';
    const head = message || '模型调用失败';
    return (code ? head + ' [' + code + ']' : head) + status;
  }
  return '模型调用失败';
}

/**
 * Describe an unexpected thrown value.
 * @param {unknown} error - thrown value.
 * @returns {string} short human message.
 */
function describeError(error) {
  if (error && typeof error === 'object' && typeof error.message === 'string') return error.message;
  return String(error || '未知错误');
}

/**
 * Abort without letting an already-settled controller throw.
 * @param {AbortController} controller - controller to abort.
 */
function abortQuietly(controller) {
  try {
    controller.abort();
  } catch {
    // Already aborted.
  }
}

/**
 * Read a bounded JSON request body.
 * @param {import('node:http').IncomingMessage} req - request.
 * @param {number} limitBytes - maximum accepted body size.
 * @returns {Promise<Record<string, unknown>>} parsed body (empty object when absent).
 */
async function readJsonBody(req, limitBytes) {
  const chunks = [];
  let total = 0;
  for await (const chunk of req) {
    total += chunk.length;
    if (total > limitBytes) throw new Error('body too large');
    chunks.push(chunk);
  }
  if (total === 0) return {};
  const text = Buffer.concat(chunks).toString('utf8');
  const parsed = JSON.parse(text);
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return {};
  return parsed;
}

/**
 * Write one JSON response with headers that keep it out of every cache.
 * @param {import('node:http').ServerResponse} res - response.
 * @param {number} status - HTTP status code.
 * @param {Record<string, unknown>} body - JSON body.
 */
function sendJson(res, status, body) {
  if (res.writableEnded || res.destroyed) return;
  let payload;
  try {
    payload = JSON.stringify(body);
  } catch {
    payload = '{"ok":false,"error":"序列化失败"}';
  }
  res.statusCode = status;
  res.setHeader('content-type', 'application/json; charset=utf-8');
  res.setHeader('cache-control', 'no-store');
  res.setHeader('x-content-type-options', 'nosniff');
  res.end(payload);
}

